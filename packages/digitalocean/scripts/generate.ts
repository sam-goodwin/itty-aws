#!/usr/bin/env bun
/**
 * generate — turn the Smithy JSON models in .generated-specs into Effect
 * SDK modules.
 *
 * Input:  .generated-specs/<service>.json  (written by scripts/convert.ts)
 * Output: src/services/<service>.ts  +  src/services/index.ts
 *
 * DigitalOcean is the simple REST case, like Fly.io: bearer auth and
 * per-op errors that are purely status-mapped onto the shared core error
 * classes. Response envelopes (`{ droplet: ... }`, `{ droplets: [...],
 * links, meta }`) are modeled as-is by the spec's response schemas, so the
 * generator needs no envelope handling — consumers unwrap.
 */
import { type SdkSpec } from "@distilled.cloud/core/codegen/generator";
import { runGeneratorCli } from "@distilled.cloud/core/codegen/cli";
import {
  NULLABLE_TRAIT,
  RAW_RESPONSE_TRAIT,
} from "@distilled.cloud/core/codegen/openapi";

/**
 * The status-mapped error classes the converter can name (its
 * `statusToErrorClass` default). They exist in core and are re-exported by
 * `src/errors.ts`, so the driver must NOT emit per-module classes for them;
 * the header imports them instead.
 */
const CORE_ERROR_CLASSES = [
  "BadRequest",
  "Conflict",
  "Forbidden",
  "NotFound",
  "UnprocessableEntity",
];

/** DigitalOcean's provider spec for the shared smithy→SDK compiler. */
const digitalOceanSpec: SdkSpec = {
  nullableTrait: NULLABLE_TRAIT,
  sourceNote: ".generated-specs",

  extraBindings: [
    {
      // Sole output member carrying a bare (array/scalar) response body —
      // the response IS the payload.
      trait: RAW_RESPONSE_TRAIT,
      binding: "rawResponse",
      pipe: "T.RawResponse()",
      rootPipe: "T.RawResponseRoot()",
    },
  ],

  // DigitalOcean's oneOf/anyOf unions (pagination links, polymorphic
  // droplet-create bodies) are plain value alternatives, not
  // key-discriminated object cases — emit the TS union with an opaque schema
  // (the REST protocol passes union content through verbatim).
  union: ({ name, caseTargets, tsRef }) => [
    `export type ${name} = ${caseTargets.map(tsRef).join(" | ") || "unknown"};`,
    `export const ${name} = /*@__PURE__*/ S.Unknown as any as S.Schema<${name}>;\n`,
  ],

  memberTraitPipes: {
    // The REST protocol wraps decoded values in `Redacted` on the way out
    // and unwraps on the way in.
    "smithy.api#sensitive": "T.SensitiveValue",
  },

  // Per-op error classes are the shared core HTTP classes (re-exported by
  // src/errors.ts) — suppress the driver's per-module class emission; the
  // header imports them instead. The REST protocol constructs them from its
  // status map.
  errors: {
    override: ({ name }) =>
      CORE_ERROR_CLASSES.includes(name) ? [] : undefined,
  },

  operationDecl: {
    contextType: "DigitalOceanOpContext",
    commonErrorType: "DigitalOceanOpError",
    commonErrorClasses: [],
    protocol: "DigitalOceanProtocol",
    retry: "Retry.Retry",
  },

  header: () =>
    `// AUTO-GENERATED by scripts/generate.ts from .generated-specs. Do not edit.\n` +
    `import * as S from "@distilled.cloud/core/schema";\n` +
    `import * as API from "@distilled.cloud/core/api";\n` +
    `import * as T from "../traits.ts";\n` +
    `import {\n` +
    `  DigitalOceanProtocol,\n` +
    `  type DigitalOceanOpError,\n` +
    `  type DigitalOceanOpContext,\n` +
    `} from "../protocol.ts";\n` +
    `import { ${CORE_ERROR_CLASSES.join(", ")} } from "../errors.ts";\n` +
    `import * as Retry from "../retry.ts";\n\n` +
    `export type { DigitalOceanOpError, DigitalOceanOpContext };\n\n`,

  // Drop error-class names the module never references (e.g. Conflict when
  // no op declares a 409) from the header import.
  postProcess: (code) => {
    const importLine = `import { ${CORE_ERROR_CLASSES.join(", ")} } from "../errors.ts";`;
    const rest = code.replace(importLine, "");
    const used = CORE_ERROR_CLASSES.filter((n) =>
      new RegExp(`\\b${n}\\b`).test(rest),
    );
    return code.replace(
      importLine,
      used.length
        ? `import { ${used.join(", ")} } from "../errors.ts";`
        : `// (no status-mapped error classes referenced)`,
    );
  },
};

runGeneratorCli({
  description: "Generate the DigitalOcean Effect SDK from the Smithy models",
  root: `${import.meta.dir}/..`,
  // The RFC-6902 patch chain (patches/<service>/*.patch.json) applies to
  // the OpenAPI document during scripts/convert.ts, not the Smithy model —
  // hence false here.
  patchesDir: false,
  spec: () => digitalOceanSpec,
});
